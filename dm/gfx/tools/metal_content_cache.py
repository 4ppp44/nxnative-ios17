"""Content cache for exact MSL + compiler binaries/arguments + SDK version.

The translation-chain identity is intentionally separate: a new translator must
still emit byte-identical MSL to reuse an old Metal compilation. Reflection is
always regenerated by the current translation chain.
"""
import atexit, ctypes, functools, hashlib, json, os, shutil, subprocess, threading, uuid
from pathlib import Path

_lock=threading.Lock()
_index=None
stats={'hit':0,'compiled':0}
_pending_receipts = 0

def root():
    return Path(os.environ.get('DM_METAL_CONTENT_CACHE',str(Path(os.environ.get('DM_ROOT','.' ))/'build/metal-content-cache')))

@functools.lru_cache(None)
def recipe(metal,metallib):
    sdk=metal[metal.index('-sdk')+1]
    tools={}
    for name in ('metal','metallib'):
        p=subprocess.check_output(['xcrun','-sdk',sdk,'--find',name],text=True).strip()
        tools[name]=hashlib.sha256(Path(p).read_bytes()).hexdigest()
    return {'metal':list(metal),'metallib':list(metallib),'tools':tools,'sdk_version':subprocess.check_output(['xcrun','-sdk',sdk,'--show-sdk-version'],text=True).strip()}

def identity(msl,metal,metallib):
    source=Path(msl).read_bytes()
    rec=recipe(tuple(metal),tuple(metallib))
    return hashlib.sha256(source+b'\0'+json.dumps(rec,sort_keys=True).encode()).hexdigest(),rec

def copy_atomic(src,dst):
    src,dst=Path(src),Path(dst);dst.parent.mkdir(parents=True,exist_ok=True)
    tmp=dst.with_name(dst.name+'.cache-'+uuid.uuid4().hex)
    try:
        cloned=False
        if os.uname().sysname=='Darwin':
            fn=ctypes.CDLL(None,use_errno=True).clonefile
            fn.argtypes=[ctypes.c_char_p,ctypes.c_char_p,ctypes.c_int];fn.restype=ctypes.c_int
            cloned=fn(os.fsencode(src),os.fsencode(tmp),0)==0
        if not cloned:shutil.copyfile(src,tmp)
        os.replace(tmp,dst)
    finally:
        if tmp.exists():tmp.unlink()

def index():
    global _index
    if _index is None:
        p=root()/'index.json';_index=json.loads(p.read_text()) if p.exists() else {}
    return _index

def save(entries):
    root().mkdir(parents=True,exist_ok=True)
    p=root()/'index.json';tmp=p.with_suffix('.tmp')
    tmp.write_text(json.dumps(entries,separators=(',',':')));os.replace(tmp,p)

# Keep exact source/compiler receipts, but avoid rewriting the growing index
# after every shader. Like upstream's content cache, cache bookkeeping must not
# dominate a full recompile. Losing an unflushed receipt only causes a recompile;
# neither an unverified library nor an old compiler recipe can become a cache hit.
def save_pending():
    global _pending_receipts
    with _lock:
        if _pending_receipts:
            save(index()); _pending_receipts = 0

atexit.register(save_pending)

def seed(msl,lib,metal,metallib,entries):
    key,rec=identity(msl,metal,metallib);lib=Path(lib).resolve()
    entries[key]={'file':str(lib),'sha256':hashlib.sha256(lib.read_bytes()).hexdigest(),'recipe':rec,'source_sha256':hashlib.sha256(Path(msl).read_bytes()).hexdigest()}

def compile(msl,air,lib,metal,metallib):
    global _pending_receipts
    key,rec=identity(msl,metal,metallib)
    with _lock:entry=index().get(key)
    if entry:
        p=Path(entry['file'])
        if p.exists() and hashlib.sha256(p.read_bytes()).hexdigest()==entry['sha256']:
            copy_atomic(p,lib)
            with _lock:stats['hit']+=1
            return
    tmp=str(lib)+'.compile-'+uuid.uuid4().hex
    try:
        subprocess.run([*metal,str(msl),'-o',str(air)],check=True)
        subprocess.run([*metallib,str(air),'-o',tmp],check=True)
        os.replace(tmp,lib)
    finally:
        if Path(tmp).exists():Path(tmp).unlink()
    # The caller may atomically rename lib (e.g. .tmp -> .metallib), so retain
    # one immutable content-addressed copy for future compilations.
    cached=root()/(key+'.metallib');copy_atomic(lib,cached)
    with _lock:
        index()[key]={'file':str(cached.resolve()),'sha256':hashlib.sha256(cached.read_bytes()).hexdigest(),'recipe':rec}
        _pending_receipts += 1; stats['compiled'] += 1
        if _pending_receipts >= 64:
            save(index()); _pending_receipts = 0
